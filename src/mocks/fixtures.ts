const getOffsetDateTime = (days: number, time: string) => {
  const d = new Date();
  d.setDate(d.getDate() + days);
  const dateStr = new Intl.DateTimeFormat('en-CA', { timeZone: 'Asia/Bangkok' }).format(d);
  return `${dateStr}T${time}:00+07:00`;
};

